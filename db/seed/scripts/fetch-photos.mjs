import { readFileSync, writeFileSync } from 'node:fs';
import sharp from 'sharp';

const UA = 'AgroTraceSeed/1.0 (educational project; https://commons.wikimedia.org)';
const ALLOWED = /^(CC0|CC BY(-SA)? \d(\.\d)?( [a-z]{2})?)$/i;
const MAX_BYTES = 300 * 1024;
const root = new URL('..', import.meta.url);
const list = JSON.parse(readFileSync(new URL('data/photos.json', root), 'utf8'));
const strip = (html) =>
  (html ?? '')
    .replace(/<[^>]+>/g, '')
    .replace(/\s+/g, ' ')
    .trim();

const rows = [];
for (const { file, title } of list) {
  const u = new URL('https://commons.wikimedia.org/w/api.php');
  const q = {
    action: 'query',
    format: 'json',
    titles: title,
    prop: 'imageinfo',
    iiprop: 'url|extmetadata|mime',
    iiurlwidth: '1024',
  };
  for (const [k, v] of Object.entries(q)) u.searchParams.set(k, v);
  const res = await fetch(u, { headers: { 'User-Agent': UA } });
  if (!res.ok) throw new Error(`${title}: HTTP ${res.status}`);
  const page = Object.values((await res.json()).query.pages)[0];
  const ii = page.imageinfo?.[0];
  if (!ii) throw new Error(`${title}: not found`);
  const m = ii.extmetadata;
  const license = strip(m.LicenseShortName?.value);
  if (!ALLOWED.test(license)) throw new Error(`${title}: license ${license} is not CC0 / CC BY / CC BY-SA`);
  const img = Buffer.from(await (await fetch(ii.thumburl, { headers: { 'User-Agent': UA } })).arrayBuffer());
  let quality = 82;
  let out;
  do {
    out = await sharp(img)
      .rotate()
      .resize(1024, 1024, { fit: 'inside', withoutEnlargement: true })
      .jpeg({ quality, mozjpeg: true })
      .toBuffer();
    quality -= 6;
  } while (out.length > MAX_BYTES && quality > 40);
  if (out.length > MAX_BYTES) throw new Error(`${title}: cannot fit into ${MAX_BYTES} bytes`);
  writeFileSync(new URL(`images/products/${file}`, root), out);
  rows.push({
    file,
    title: title.replace(/^File:/, ''),
    author: strip(m.Artist?.value) || 'unknown',
    license,
    licenseUrl: m.LicenseUrl?.value ?? '',
    url: ii.descriptionurl,
  });
  console.log(`${file}: ${out.length} bytes, ${license}`);
}

const md = [
  '# Attribution',
  '',
  'Product photos in `images/products/` come from Wikimedia Commons. Each file was downscaled to at most',
  '1024 px on the longer side and re-encoded as JPEG without metadata (`scripts/fetch-photos.mjs`); no other',
  'changes were made. The seed derives WebP 96 px and 480 px variants from them (FR-FILE-04). Each photo keeps',
  'the license of its original; files under CC BY-SA are shared under the same license.',
  '',
  'Logos (`images/logos/*.svg`) and avatars (`images/avatars/*`) are generated by `src/gen-images.ts` and are',
  'part of this project.',
  '',
  '| File | Original title | Author | License | Source |',
  '|---|---|---|---|---|',
  ...rows.map(
    (r) =>
      `| \`${r.file}\` | ${r.title} | ${r.author.replace(/\|/g, '\|')} | ${r.licenseUrl ? `[${r.license}](${r.licenseUrl})` : r.license} | <${r.url}> |`,
  ),
  '',
].join('\n');
writeFileSync(new URL('ATTRIBUTION.md', root), md);
