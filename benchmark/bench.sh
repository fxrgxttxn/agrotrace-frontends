#!/usr/bin/env bash
# All logic of `./at.sh bench <sub>` lives here (at.sh only delegates one line, spec Global
# Constraints). Talks exclusively to the `agrotrace-bench` compose project (isolated stand, no
# published ports) — never touches the shared `agrotrace` project the other streams use.
set -euo pipefail
# Absolute path to this script, taken before the cd below: `all` re-invokes itself per step, and
# $0 may be relative to the caller's directory (at.sh execs "./benchmark/bench.sh").
SELF="$(cd "$(dirname "$0")" && pwd)/$(basename "$0")"
cd "$(dirname "$0")"

DC="docker compose -p agrotrace-bench -f docker-compose.yml"
# Ruling B3: the live stand's profile/durability live in benchmark/.env — the file docker compose
# itself reads for variable interpolation (project directory = benchmark/, the compose file's own
# directory). `up` writes it; every later `docker compose` call — from this script *or* a raw
# `docker compose -p agrotrace-bench -f benchmark/docker-compose.yml run ...` typed by hand — then
# resolves PG_PROFILE/REDIS_PROFILE/DURABILITY/PG_SYNCHRONOUS_COMMIT/REDIS_APPENDFSYNC to the
# profile that is actually up, instead of silently recreating the DBMS containers with compose
# defaults. docker-compose.yml has no defaults for these five (`${VAR:?...}`), so with no .env
# (no `up` yet) compose refuses to start anything rather than guess a profile.
STATE_FILE=".env"
DURABILITY_FILE="durability.conf"
RESULTS_DIR="results"
PUBLISH_DIR="../docs/reports/data"

cmd="${1:-help}"; shift || true

usage() {
  echo "usage: ./at.sh bench <up|down|env|test|lint|gen|load|run|plot|report|publish|all> [args]" >&2
  echo "       ./at.sh bench up [pg_profile:default|tuned] [redis_profile:default|tuned] [durability:strict|relaxed]" >&2
  exit 2
}

check_profile()    { case "$1" in default|tuned) ;; *) echo "bench: profile must be default or tuned, got '$1'" >&2; usage ;; esac; }
check_durability() { case "$1" in strict|relaxed) ;; *) echo "bench: durability must be strict or relaxed, got '$1'" >&2; usage ;; esac; }

# Durability (strict|relaxed) -> concrete setting, read from durability.conf — the single source
# of truth also parsed by agrobench.config (used by tests/test_env.py's expected values and by
# agrobench.load_redis, which restores this exact appendfsync after the bulk pipeline load).
durability_setting() { # $1=strict|relaxed $2=pg_synchronous_commit|redis_appendfsync
  local value
  value="$(grep -m1 "^$1\.$2=" "$DURABILITY_FILE" | cut -d= -f2)"
  [ -n "$value" ] || { echo "bench: no $2 entry for durability '$1' in $DURABILITY_FILE" >&2; exit 1; }
  echo "$value"
}
sync_commit_for()   { durability_setting "$1" pg_synchronous_commit; }
appendfsync_for()   { durability_setting "$1" redis_appendfsync; }

write_state() { # $1=pg_profile $2=redis_profile $3=durability
  local sc af
  sc="$(sync_commit_for "$3")"; af="$(appendfsync_for "$3")"
  {
    echo "# Generated by benchmark/bench.sh 'up' — the live stand's profile (ruling B3). Read by"
    echo "# docker compose for interpolation and sourced by bench.sh. Do not edit by hand."
    echo "PG_PROFILE=$1"
    echo "REDIS_PROFILE=$2"
    echo "DURABILITY=$3"
    echo "PG_SYNCHRONOUS_COMMIT=$sc"
    echo "REDIS_APPENDFSYNC=$af"
  } > "$STATE_FILE"
}

# Every subcommand except up/down needs a stand that `up` already brought up and recorded here.
load_state() {
  [ -f "$STATE_FILE" ] || { echo "bench: no stand is up — run './at.sh bench up' first" >&2; exit 1; }
  set -a; . "./$STATE_FILE"; set +a
}

do_up() {
  local pg="${1:-default}" rd="${2:-default}" dur="${3:-relaxed}"
  check_profile "$pg"; check_profile "$rd"; check_durability "$dur"
  write_state "$pg" "$rd" "$dur"
  rm -f .bench-state  # pre-B3 state file, superseded by .env
  load_state
  # --force-recreate: the profile .conf files are bind-mounted, so an edited file under an unchanged
  # path would otherwise keep running with the old settings.
  $DC up -d --build --force-recreate --wait bench-postgres bench-redis
  do_env
}

do_down() {
  # `down` must work with or without a recorded stand: compose still interpolates the whole file,
  # so with no .env it gets throwaway values (they only name config files; nothing is started).
  if [ -f "$STATE_FILE" ]; then
    load_state
  else
    export PG_PROFILE=default REDIS_PROFILE=default DURABILITY=relaxed
    export PG_SYNCHRONOUS_COMMIT=off REDIS_APPENDFSYNC=everysec
  fi
  $DC down --volumes "$@"
  rm -f "$STATE_FILE" .bench-state
}

do_env() {
  load_state
  export DOCKER_VERSION DOCKER_COMPOSE_VERSION
  DOCKER_VERSION="$(docker --version)"
  DOCKER_COMPOSE_VERSION="$(docker compose version --short 2>/dev/null || echo unknown)"

  # Actual limits applied to the *running* containers, introspected via `docker inspect` (host has
  # docker; bench-runner, where agrobench.env actually runs, has no docker socket) rather than
  # just repeating the declared agrobench.config.RESOURCE_LIMITS constant — env.json should report
  # what the stand really got, not what docker-compose.yml merely asked for.
  local pg_cid rd_cid
  pg_cid="$($DC ps -q bench-postgres)"
  rd_cid="$($DC ps -q bench-redis)"
  [ -n "$pg_cid" ] && [ -n "$rd_cid" ] || {
    echo "bench: env needs a running stand — run './at.sh bench up' first" >&2; exit 1; }
  export PG_LIMITS_CPUS PG_LIMITS_MEM_BYTES REDIS_LIMITS_CPUS REDIS_LIMITS_MEM_BYTES
  PG_LIMITS_CPUS="$(docker inspect "$pg_cid" --format '{{.HostConfig.NanoCpus}}')"
  PG_LIMITS_MEM_BYTES="$(docker inspect "$pg_cid" --format '{{.HostConfig.Memory}}')"
  REDIS_LIMITS_CPUS="$(docker inspect "$rd_cid" --format '{{.HostConfig.NanoCpus}}')"
  REDIS_LIMITS_MEM_BYTES="$(docker inspect "$rd_cid" --format '{{.HostConfig.Memory}}')"

  $DC run --rm bench-runner python -m agrobench.env
}

# Copies the consolidated result set the report is built from (Task 5) out of the git-ignored
# benchmark/results/ into the committed docs/reports/data/. Runs on the host: bench-runner only
# mounts benchmark/, not docs/.
do_publish() {
  mkdir -p "$PUBLISH_DIR/plans" "$PUBLISH_DIR/redis"
  local f
  for f in measurements.csv measurements_median.csv load.csv memory.csv settings.csv env.json run_meta.json; do
    [ -f "$RESULTS_DIR/$f" ] || { echo "bench: publish: $RESULTS_DIR/$f missing — run the benchmark first" >&2; exit 1; }
    cp "$RESULTS_DIR/$f" "$PUBLISH_DIR/$f"
  done
  rm -f "$PUBLISH_DIR"/plans/*.txt "$PUBLISH_DIR"/redis/*.txt
  cp "$RESULTS_DIR"/plans/*.txt "$PUBLISH_DIR/plans/"
  cp "$RESULTS_DIR"/redis/*.txt "$PUBLISH_DIR/redis/"
  echo "bench: published results to $PUBLISH_DIR"
}

# Full matrix (spec §13.6; Task 4 controller decision): each DBMS in {default,tuned} x
# {strict,relaxed}. One `up` per (profile, durability) brings *both* DBMS up in that profile;
# `run` then measures PostgreSQL and Redis one after the other (the other DBMS idle), 3
# repetitions each — a {PG profile} x {Redis profile} cross product would only re-measure each
# DBMS in the same configuration while its idle neighbour's profile changes. Starts from clean
# volumes; data is generated once and reloaded fresh for every configuration (load time and size
# are part of the results). Extra args are passed through to every `run`.
do_all() {
  local started started_iso finished
  started="$(date +%s)"; started_iso="$(date -u +%Y-%m-%dT%H:%M:%SZ)"
  rm -rf "$RESULTS_DIR"/raw "$RESULTS_DIR"/plans "$RESULTS_DIR"/redis "$RESULTS_DIR"/settings "$RESULTS_DIR"/load
  rm -f "$RESULTS_DIR"/measurements.csv "$RESULTS_DIR"/measurements_median.csv "$RESULTS_DIR"/load.csv \
        "$RESULTS_DIR"/memory.csv "$RESULTS_DIR"/settings.csv "$RESULTS_DIR"/run_meta.json
  "$SELF" down
  "$SELF" up default default relaxed
  "$SELF" gen
  local profile dur
  for profile in default tuned; do
    for dur in strict relaxed; do
      "$SELF" up "$profile" "$profile" "$dur"
      "$SELF" load
      "$SELF" run "$@"
    done
  done
  finished="$(date +%s)"
  printf '{\n  "started_at": "%s",\n  "finished_at": "%s",\n  "duration_seconds": %s,\n  "command": "./at.sh bench all%s"\n}\n' \
    "$started_iso" "$(date -u +%Y-%m-%dT%H:%M:%SZ)" "$((finished - started))" "${*:+ $*}" > "$RESULTS_DIR/run_meta.json"
  # Task 5 adds plot.py/report_tables.py; until then `all` stops after the measurements.
  if [ -f agrobench/plot.py ]; then "$SELF" plot; fi
  if [ -f agrobench/report_tables.py ]; then "$SELF" report; fi
  do_publish
  echo "bench: all done in $((finished - started)) s"
}

case "$cmd" in
  up)   do_up "$@" ;;
  down) do_down "$@" ;;
  env)  do_env ;;
  test) load_state; $DC run --rm bench-runner python -m pytest tests "$@" ;;
  lint) load_state; $DC run --rm bench-runner python -m ruff check agrobench tests "$@" ;;
  gen)  load_state; $DC run --rm bench-runner python -m agrobench.generate "$@" ;;
  # PostgreSQL first (COPY -> indexes -> ANALYZE), then Redis (pipeline load, then durability
  # mode restored) — independent datastores, order between the two does not matter otherwise.
  load)
    load_state
    $DC run --rm bench-runner python -m agrobench.load_pg "$@"
    $DC run --rm bench-runner python -m agrobench.load_redis "$@" ;;
  run)     load_state; $DC run --rm bench-runner python -m agrobench.run "$@" ;;
  plot)    load_state; $DC run --rm bench-runner python -m agrobench.plot "$@" ;;
  report)  load_state; $DC run --rm bench-runner python -m agrobench.report_tables "$@" ;;
  publish) do_publish ;;
  all)     do_all "$@" ;;
  help|*) usage ;;
esac
