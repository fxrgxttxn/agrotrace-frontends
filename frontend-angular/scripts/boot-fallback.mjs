import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const RU = join(here, '../../packages/i18n/locales/ru.json');
const INDEX = join(here, '../src/index.html');
const TEXTS = join(here, '../src/boot-texts.generated.ts');
const START = '<!-- boot-fallback (generated by scripts/boot-fallback.mjs) -->';
const END = '<!-- /boot-fallback -->';

const escape = (s) =>
  s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');

export function generate() {
  const ru = JSON.parse(readFileSync(RU, 'utf8'));
  const failed = ru.empty?.pageLoadFailed;
  const retry = ru.action?.retry;
  if (typeof failed !== 'string' || typeof retry !== 'string')
    throw new Error('i18n: empty.pageLoadFailed / action.retry');
  const block = [
    START,
    '    <style>',
    '      #boot-fallback { visibility: hidden; animation: boot-fallback 0s 10s forwards; }',
    '      @keyframes boot-fallback { to { visibility: visible; } }',
    '    </style>',
    '    <main class="at-page" id="boot-fallback" style="max-width: 30rem">',
    '      <article class="at-card">',
    '        <div class="at-empty">',
    `          <p class="at-empty__text">${escape(failed)}</p>`,
    `          <a class="at-button" data-variant="primary" href="">${escape(retry)}</a>`,
    '        </div>',
    '      </article>',
    '    </main>',
    `    ${END}`,
  ].join('\n');
  const html = readFileSync(INDEX, 'utf8');
  const a = html.indexOf(START);
  const b = html.indexOf(END);
  if (a < 0 || b < a) throw new Error('src/index.html: boot-fallback markers missing');
  const index = html.slice(0, a) + block + html.slice(b + END.length);
  const texts =
    `export const PAGE_LOAD_FAILED = ${JSON.stringify(failed)};\n` +
    `export const RETRY = ${JSON.stringify(retry)};\n`;
  return { index, texts };
}

const { index, texts } = generate();
if (process.argv.includes('--check')) {
  if (readFileSync(INDEX, 'utf8') !== index || readFileSync(TEXTS, 'utf8') !== texts) {
    console.error(
      'boot-fallback: src/index.html / src/boot-texts.generated.ts are stale — run node scripts/boot-fallback.mjs',
    );
    process.exit(1);
  }
} else {
  writeFileSync(INDEX, index);
  writeFileSync(TEXTS, texts);
}
