/**
 * Generates src/contract/operations.generated.ts from the bundled contract (contracts/openapi.yaml): every operation's
 * method, path template and the extensions the mock enforces (x-roles, x-org-admin, x-idempotent, x-rate-limit, x-sort,
 * x-report-access) plus whether Bearer security applies. The browser bundle never carries the whole contract (and never
 * runs Ajv — CSP forbids eval); tests check that the generated table matches the contract.
 * Run: ./at.sh pnpm --filter @agrotrace/mock-api gen
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { operationTable } from './contract-table.js';

const out = fileURLToPath(new URL('../src/contract/operations.generated.ts', import.meta.url));
const table = await operationTable();
writeFileSync(
  out,
  [
    '// Generated by scripts/gen-contract.ts from contracts/openapi.yaml — do not edit by hand.',
    "import type { OperationMeta } from './types.js';",
    '',
    `export const OPERATIONS: readonly OperationMeta[] = ${JSON.stringify(table, null, 2)};`,
    '',
  ].join('\n'),
);
console.log(`operations: ${table.length}`);
